const seededTenants = new Set<string>();

export async function ensureConstructionNcms(
  db: {
    ncmCode: {
      createMany: (args: {
        data: Array<{ code: string; description: string }>;
        skipDuplicates?: boolean;
      }) => Promise<unknown>;
    };
  },
  tenantSlug?: string,
): Promise<void> {
  if (tenantSlug && seededTenants.has(tenantSlug)) return;
  await db.ncmCode.createMany({
    data: CONSTRUCTION_HARDWARE_NCMS.map((r) => ({
      code: r.code,
      description: r.description,
    })),
    skipDuplicates: true,
  });
  if (tenantSlug) seededTenants.add(tenantSlug);
}
